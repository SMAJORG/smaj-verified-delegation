import assert from "node:assert/strict";
import test from "node:test";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { NextRequest } from "next/server";
import { POST as enterDemo } from "@/app/api/auth/demo/route";
import { GET as sessionInfo, DELETE as logout, POST as tokenLogin } from "@/app/api/auth/session/route";
import { GET as list, POST as create } from "@/app/api/delegations/route";
import { GET as detail } from "@/app/api/delegations/[id]/route";
import { GET as events } from "@/app/api/delegations/[id]/events/route";
import { POST as approve } from "@/app/api/delegations/[id]/approve/route";
import { POST as execute } from "@/app/api/delegations/[id]/execute/route";
import { POST as routeTask } from "@/app/api/tasks/route";
import { GET as jobs } from "@/app/api/jobs/route";
import { GET as connections, POST as connect } from "@/app/api/connections/route";
import { GET as store } from "@/app/api/store/route";
import { getDemoDatabase, issueDemoSession, readDemoSession, DEMO_TTL_SECONDS, cleanupDemoSessions } from "@/src/server/demo-sessions";
import { createUserSession, requireActorSession, SESSION_COOKIE } from "@/src/server/auth";
import { workspaceDatabase } from "@/src/server/demo-workspace";
import { DelegationWorkflow } from "@/src/server/workflow";
import { jobs as fixtureJobs, plan as fixturePlan } from "@/tests/fixtures";

test("complete restricted demo login, approval, execution, isolation, expiry and logout flow", async () => {
  const directory = mkdtempSync(join(tmpdir(), "smaj-demo-flow-"));
  const previous = { ...process.env };
  const originalFetch = globalThis.fetch;
  process.env.SMAJ_HACKATHON_DB_PATH = join(directory, "demo.sqlite");
  process.env.SMAJ_DELEGATION_DB_PATH = join(directory, "production.sqlite");
  process.env.SMAJ_DEMO_AUTH_ENABLED = "true";
  process.env.SMAJ_AI_SESSION_SECRET = "test-only-session-secret-at-least-32";
  process.env.SMAJ_DEMO_ACCESS_TOKEN = "test-only-access-token-at-least-32";
  delete process.env.META_API_KEY;
  process.env.SMAJ_PRODUCTION_WRITES_ENABLED = "true";
  process.env.SMAJ_REAL_PI_PAYMENTS_ENABLED = "true";
  globalThis.fetch = async () => { throw new Error("Demo must never contact a live service"); };
  const request = (path: string, cookie = "", method = "GET", body?: unknown, origin = "https://demo.example") => new NextRequest(`https://demo.example${path}`, {
    method, headers: { cookie, origin, "Content-Type": "application/json", "Idempotency-Key": `test-${crypto.randomUUID()}` },
    ...(body !== undefined ? { body: JSON.stringify(body) } : {}),
  });
  try {
    assert.equal((await list(request("/api/delegations"))).status, 401);
    assert.equal((await enterDemo(request("/api/auth/demo", "", "POST", {}, "https://evil.example"))).status, 403);
    const proxied = new NextRequest("http://localhost/api/auth/demo", { method: "POST", headers: { host: "judging.example", origin: "https://judging.example", "x-forwarded-proto": "https, http", "content-type": "application/json" }, body: "{}" });
    const proxiedResponse = await enterDemo(proxied);
    assert.equal(proxiedResponse.status, 200);
    assert.match(proxiedResponse.headers.get("set-cookie")!, /Secure/i);
    await logout(request("/api/auth/session", proxiedResponse.headers.get("set-cookie")!.split(";")[0], "DELETE"));
    const response = await enterDemo(request("/api/auth/demo", "", "POST", { actorId: "production-user", role: "admin" }));
    assert.equal(response.status, 200);
    const header = response.headers.get("set-cookie")!;
    assert.match(header, /HttpOnly/i); assert.match(header, /SameSite=strict/i); assert.match(header, /Secure/i); assert.match(header, /Max-Age=3600/);
    const cookie = header.split(";")[0];
    const payload = await response.json();
    assert.equal(payload.sandbox, true);
    assert.equal(JSON.stringify(payload).includes("hackathon_"), false);
    const actor = requireActorSession(request("/", cookie));
    assert.match(actor.actorId, /^hackathon:/);
    assert.equal(actor.sandbox, true);
    assert.equal((await sessionInfo(request("/api/auth/session", cookie))).headers.get("cache-control"), "no-store");
    const workspace = await (await list(request("/api/delegations", cookie))).json();
    assert.equal(workspace.delegations.length, 3);
    assert.deepEqual(new Set(workspace.delegations.map((item: { status: string }) => item.status)), new Set(["awaiting_approval", "approved", "verified"]));
    const verified = workspace.delegations.find((item: { status: string }) => item.status === "verified");
    assert.equal(verified.receipt.proof.scope.productionSideEffects, false);
    assert.equal(verified.receipt.proof.scope.realPiPayment, false);
    assert.ok(verified.receipt.proof.checks.every((check: { passed: boolean }) => check.passed));
    const duplicate = await enterDemo(request("/api/auth/demo", cookie, "POST", {}));
    assert.equal(duplicate.status, 200); assert.equal(duplicate.headers.get("set-cookie"), null);
    const otherResponse = await enterDemo(request("/api/auth/demo", "", "POST", {}));
    const otherCookie = otherResponse.headers.get("set-cookie")!.split(";")[0];
    const context = { params: Promise.resolve({ id: verified.id }) };
    assert.equal((await detail(request("/api/delegations/id", otherCookie), context)).status, 404);
    assert.equal((await approve(request("/api/delegations/id/approve", otherCookie, "POST", {}), context)).status, 404);
    assert.equal((await execute(request("/api/delegations/id/execute", otherCookie, "POST", {}), context)).status, 404);
    assert.equal((await events(request("/api/delegations/id/events", otherCookie), context)).status, 404);
    const stream = await events(request("/api/delegations/id/events", cookie), context);
    assert.equal(stream.status, 200);
    const reader = stream.body!.getReader();
    assert.match(new TextDecoder().decode((await reader.read()).value), /event: delegation/);
    await reader.cancel();
    assert.equal((await routeTask(request("/api/tasks", cookie, "POST", { task: "Find remote developer opportunities" }))).status, 200);
    const newResponse = await create(request("/api/delegations", cookie, "POST", { goal: "Find suitable frontend engineering opportunities", candidateName: "Sample Judge", skills: ["React"], maxApplications: 2 }));
    assert.equal(newResponse.status, 201);
    const created = (await newResponse.json()).delegation;
    const newContext = { params: Promise.resolve({ id: created.id }) };
    assert.equal((await execute(request("/api/delegations/id/execute", cookie, "POST", {}), newContext)).status, 409);
    assert.equal((await approve(request("/api/delegations/id/approve", cookie, "POST", {}), newContext)).status, 200);
    const result = await execute(request("/api/delegations/id/execute", cookie, "POST", {}), newContext);
    assert.equal((await result.json()).delegation.status, "verified");
    assert.equal((await jobs(request("/api/jobs", cookie))).status, 200);
    assert.equal((await connections(request("/api/connections", cookie))).status, 200);
    assert.equal((await connect(request("/api/connections", cookie, "POST", { serviceId: "store", connected: true }))).status, 200);
    assert.equal((await store(request("/api/store", cookie))).status, 200);
    const regular = createUserSession({ sub: "production-user" });
    const regularRequest = request("/", `${SESSION_COOKIE}=${regular.value}`);
    assert.notEqual(workspaceDatabase(regularRequest), workspaceDatabase(request("/", cookie)));
    const productionWorkflow = new DelegationWorkflow({ database: workspaceDatabase(regularRequest), jobsAdapter: { sourceUrl: "test://production", listJobs: async () => fixtureJobs }, planner: { plan: async () => fixturePlan } });
    const productionTask = await productionWorkflow.create("production-user", { goal: "Private production task must stay inaccessible", candidateName: "Real Account", skills: ["React"] }, "production-create");
    assert.equal((await detail(request("/api/delegations/id", cookie), { params: Promise.resolve({ id: productionTask.id }) })).status, 404);
    assert.equal(productionWorkflow.list("production-user").length, 1);
    assert.equal((await (await list(request("/api/delegations", cookie))).json()).delegations.some((item: { id: string }) => item.id === productionTask.id), false);
    assert.equal((await enterDemo(request("/api/auth/demo", `${SESSION_COOKIE}=${regular.value}`, "POST", {}))).status, 409);
    assert.equal((await tokenLogin(request("/api/auth/session", "", "POST", { accessToken: process.env.SMAJ_DEMO_ACCESS_TOKEN }))).status, 200);
    assert.equal((await list(request("/api/delegations", `${cookie}tampered`))).status, 401);
    const timed = issueDemoSession(getDemoDatabase(), 1000);
    assert.equal(readDemoSession(timed.value, getDemoDatabase(), 1001).sandbox, true);
    assert.throws(() => readDemoSession(timed.value, getDemoDatabase(), 1000 + DEMO_TTL_SECONDS * 1000));
    cleanupDemoSessions();
    process.env.SMAJ_DEMO_AUTH_ENABLED = "false";
    assert.equal((await enterDemo(request("/api/auth/demo", "", "POST", {}))).status, 403);
    assert.equal((await list(request("/api/delegations", cookie))).status, 401);
    process.env.SMAJ_DEMO_AUTH_ENABLED = "true";
    assert.equal((await logout(request("/api/auth/session", cookie, "DELETE"))).status, 200);
    assert.equal((await list(request("/api/delegations", cookie))).status, 401);
    assert.equal((getDemoDatabase().prepare("SELECT COUNT(*) AS count FROM delegations WHERE owner_id = ?").get(actor.actorId) as { count: number }).count, 0);
  } finally {
    globalThis.fetch = originalFetch;
    for (const key of Object.keys(process.env)) if (!(key in previous)) delete process.env[key];
    Object.assign(process.env, previous);
  }
});
